"""Run all stages: load -> clean -> metadata -> dedupe -> status -> chunk -> index. Each drop is reported with a reason."""
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

from ticketpilot.config import ROOT
from ticketpilot.embeddings import Embedder
from ticketpilot.ingest.chunk import STRATEGIES
from ticketpilot.ingest.clean import clean
from ticketpilot.ingest.dedupe import THRESHOLD, dedupe, jaccard, shingles
from ticketpilot.ingest.load import load_dir
from ticketpilot.ingest.metadata import make_document, resolve_status, split_front_matter
from ticketpilot.ingest.model import Document, Dropped, Quarantined
from ticketpilot.retrieval import Index

DEFAULT_KB = ROOT / "data" / "kb_raw"
DEFAULT_INDEX = ROOT / "data" / "index"
DEFAULT_REPORT = ROOT / "docs" / "a4-ingest-report.md"
PAIRS_PATH = ROOT / "evals" / "a4_dedupe_pairs.jsonl"


@dataclass
class IngestResult:
    files_in: int
    docs: list[Document]
    quarantined: list[Quarantined]
    dropped: list[Dropped]
    status_overrides: list[tuple[str, str, str]] = field(default_factory=list)  # doc_id, declared, derived


def parse_file(path: Path) -> Document | None:
    from ticketpilot.ingest.load import load_file
    raw = load_file(path)
    if isinstance(raw, Quarantined):
        return None
    meta, body = split_front_matter(raw.text)
    return make_document(raw.path, meta, clean(body))


def ingest(kb_dir: Path = DEFAULT_KB, threshold: float = THRESHOLD) -> IngestResult:
    loaded, quarantined = load_dir(kb_dir)
    files_in = len(loaded) + len(quarantined)
    docs: list[Document] = []
    for raw in loaded:
        meta, body = split_front_matter(raw.text)
        body = clean(body)
        if not body:
            quarantined.append(Quarantined(raw.path, "empty"))
            continue
        docs.append(make_document(raw.path, meta, body))
    kept, dropped = dedupe(docs, threshold)
    declared = {d.doc_id: d.status for d in kept}
    resolve_status(kept)
    overrides = [(d.doc_id, declared[d.doc_id], d.status) for d in kept if declared[d.doc_id] != d.status]
    return IngestResult(files_in, kept, quarantined, dropped, overrides)


def build_indexes(docs: list[Document], out_root: Path, embedder: Embedder | None = None) -> dict[str, int]:
    """Write data/index/<strategy>/ for each chunking strategy plus a docs table; returns chunks per strategy."""
    out_root.mkdir(parents=True, exist_ok=True)
    with (out_root / "docs.jsonl").open("w") as f:
        f.writelines(json.dumps(asdict(d)) + "\n" for d in docs)
    counts = {}
    for name, fn in STRATEGIES.items():
        chunks = [c for d in docs for c in fn(d)]
        Index.build(chunks, embedder).save(out_root / name)
        counts[name] = len(chunks)
    return counts


def score_pairs(pairs_path: Path = PAIRS_PATH) -> list[dict]:
    rows = []
    for line in pairs_path.read_text().splitlines():
        p = json.loads(line)
        a, b = parse_file(ROOT / p["a"]), parse_file(ROOT / p["b"])
        rows.append({**p, "jaccard": round(jaccard(shingles(a.body), shingles(b.body)), 3)})
    return rows


def choose_threshold(rows: list[dict]) -> tuple[float, float, float]:
    """Midpoint between the lowest true-duplicate score and the highest score of any labelled non-duplicate, including
    versions of one policy (which the explicit-version rule exempts anyway; the threshold should not depend on it alone).
    Returns (threshold, lowest_dup, highest_nondup)."""
    lo = min(r["jaccard"] for r in rows if r["duplicate"])
    hi = max(r["jaccard"] for r in rows if not r["duplicate"])
    return round((lo + hi) / 2, 2), lo, hi


def write_report(result: IngestResult, counts: dict[str, int], path: Path = DEFAULT_REPORT,
                 pair_rows: list[dict] | None = None) -> None:
    L = ["# A4 ingestion report", "",
         "Generated by `python -m ticketpilot.ingest`; do not edit by hand.", "",
         "## Counts", "",
         f"- Files in: {result.files_in}",
         f"- Documents kept: {len(result.docs)}",
         f"- Duplicates dropped: {len(result.dropped)}",
         f"- Quarantined: {len(result.quarantined)}",
         *(f"- Chunks, `{k}`: {v}" for k, v in counts.items()), ""]
    L += ["## Kept documents", "", "| doc_id | title | version | effective | status | supersedes | inferred |", "|---|---|---|---|---|---|---|"]
    L += [f"| {d.doc_id} | {d.title} | {d.version} | {d.effective_date or 'unknown'} | {d.status} | {d.supersedes or '-'} "
          f"| {', '.join(d.inferred) or '-'} |" for d in result.docs]
    L += ["", "## Dropped duplicates", "", "| file | reason | kept instead | Jaccard |", "|---|---|---|---|"]
    L += [f"| {x.path} | {x.reason} | {x.kept} | {x.jaccard} |" for x in result.dropped]
    L += ["", "## Quarantined", "", "| file | reason |", "|---|---|"]
    L += [f"| {q.path} | {q.reason} |" for q in result.quarantined] or ["| (none) | |"]
    if result.quarantined:
        L += ["", "`needs_ocr` files are not indexed: their content is unavailable to retrieval until OCR is added."]
    L += ["", "## Status derived across versions", "",
          "Declared status is overridden when a newer version of the same policy exists.", "",
          "| doc_id | declared | derived |", "|---|---|---|"]
    L += [f"| {a} | {b} | {c} |" for a, b, c in result.status_overrides] or ["| (none) | | |"]
    if pair_rows:
        t, lo, hi = choose_threshold(pair_rows)
        L += ["", "## Near-duplicate threshold", "",
              f"Labelled pairs (`evals/a4_dedupe_pairs.jsonl`, labels set by construction in the generator): lowest "
              f"true-duplicate Jaccard {lo}, highest score of any non-duplicate pair {hi} (two versions of one policy), "
              f"so the midpoint is {t}; the pipeline uses {THRESHOLD}. Pairs of different explicit versions are also "
              "exempt from dedupe, because they are history, not duplicates.", "",
              "| a | b | duplicate | exempt by version | Jaccard |", "|---|---|---|---|---|"]
        L += [f"| {r['a'].split('/')[-1]} | {r['b'].split('/')[-1]} | {r['duplicate']} | {r['exempt_by_version']} | {r['jaccard']} |"
              for r in pair_rows]
    path.write_text("\n".join(L) + "\n")

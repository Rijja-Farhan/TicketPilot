"""A4 stale-data example: do old policy versions reach the answer?

Before: fixed-size chunks, dense retrieval, no status filter, passages without version headers (the naive setup).
After: the shipped path, `policies.answer` (structured chunks with version header, status filter, derived status).
Live LLM run (uses LLM_PROVIDER from .env). Writes docs/a4-stale-example.md.
"""
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ticketpilot import llm, policies  # noqa: E402
from ticketpilot.config import INDEX_DIR, load_settings  # noqa: E402
from ticketpilot.retrieval import ALL_STATUSES, Index  # noqa: E402

NAIVE_PROMPT = ("Answer the support agent's question using only the passages below. Be brief.\n\nPASSAGES:\n{passages}")


def norm(s: str) -> str:
    s = unicodedata.normalize("NFKC", s).lower().replace("**", "")
    s = re.sub(r"£\s*(\d[\d.,]*)", r"\1 gbp", s)           # "£750" -> "750 gbp"
    s = re.sub(r"\s+%", "%", s)                              # "1 %" -> "1%"
    return s.replace(" of the ", " of ")


def verdict(answer: str, q: dict) -> str:
    """wrong = only superseded values; mixed = hedges across versions; ok = only the current value; unclear."""
    a = norm(answer)
    stale = any(norm(v) in a for v in q["stale_values"])
    current = any(norm(g["must_contain"]) in a for g in q["gold"])
    return "mixed" if stale and current else "wrong" if stale else "ok" if current else "unclear"


def main() -> None:
    qs = [q for q in map(json.loads, (ROOT / "evals" / "a4_retrieval.jsonl").read_text().splitlines()) if "stale_values" in q]
    naive_index = Index.load(INDEX_DIR / "fixed")
    L = ["# A4 stale-data example (generated by `evals/run_a4_stale.py`)", "",
         f"Provider: {load_settings().provider}. Verdicts: wrong = only superseded values, mixed = hedges across versions, ok = only the current value.", "",
         "| # | question | before: retrieved | before | after |", "|---|---|---|---|---|"]
    detail = []
    for q in qs:
        hits = naive_index.search(q["q"], k=3, mode="dense", statuses=ALL_STATUSES)
        passages = "\n\n".join(f"[{h.chunk.title}]\n{h.chunk.text}" for h in hits)
        before = llm.complete([{"role": "system", "content": NAIVE_PROMPT.format(passages=passages)},
                               {"role": "user", "content": q["q"]}])
        before_text = before.text if before.ok else f"(error {before.error.code})"
        after_text = policies.answer(q["q"])
        ids = ", ".join(f"{h.chunk.doc_id}" for h in hits)
        L.append(f"| {q['id']} | {q['q']} | {ids} | {verdict(before_text, q)} | {verdict(after_text, q)} |")
        detail += [f"### #{q['id']} {q['q']}", "", f"**Before** (retrieved: {ids})", "", f"> {before_text}", "",
                   "Top retrieved chunk:", "", "```", hits[0].chunk.text if hits else "", "```", "",
                   "**After**", "", f"> {after_text}", ""]
    out = ROOT / "docs" / "a4-stale-example.md"
    out.write_text("\n".join(L + ["", "## Detail", ""] + detail) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()

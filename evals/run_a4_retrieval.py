"""A4 retrieval eval: chunking (fixed, structured) x retriever (bm25, dense, hybrid) on evals/a4_retrieval.jsonl.

Two conditions: `unfiltered` searches every status (shows how each retriever copes with stale and draft chunks) and
`default` searches current chunks only (what the assistant ships). Writes docs/a4-retrieval-grid.md.
Usage: python evals/run_a4_retrieval.py [--embedder fastembed|hash]
"""
import argparse
import json
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ticketpilot.embeddings import get_embedder  # noqa: E402
from ticketpilot.ingest.chunk import STRATEGIES  # noqa: E402
from ticketpilot.ingest.pipeline import ingest  # noqa: E402
from ticketpilot.retrieval import ALL_STATUSES, CURRENT, Index  # noqa: E402

QUESTIONS = ROOT / "evals" / "a4_retrieval.jsonl"
GRID = ROOT / "docs" / "a4-retrieval-grid.md"
MODES = ("bm25", "dense", "hybrid")
CONDITIONS = {"unfiltered": ALL_STATUSES, "default": CURRENT}


def norm(s: str) -> str:
    return unicodedata.normalize("NFKC", s).lower().replace("**", "")


def satisfied(item: dict, hit) -> bool:
    return hit.chunk.doc_id == item["doc"] and norm(item["must_contain"]) in norm(hit.chunk.text)


def evaluate(index: Index, mode: str, statuses, questions: list[dict], status_of: dict[str, str]) -> dict:
    answerable = [q for q in questions if q["gold"]]
    recall = rr = stale = 0.0
    misses = []
    for q in answerable:
        hits = index.search(q["q"], k=3, mode=mode, statuses=statuses)
        ok = all(any(satisfied(g, h) for h in hits) for g in q["gold"])
        recall += ok
        first = next((r for r, h in enumerate(hits, 1) if any(satisfied(g, h) for g in q["gold"])), None)
        rr += 1 / first if first else 0
        top_status = status_of.get(hits[0].chunk.doc_id) if hits else None
        stale += bool(hits) and top_status != "current"
        if not ok:
            misses.append((q["id"], hits[0].chunk.doc_id if hits else None))
    n = len(answerable)
    return {"n": n, "recall": int(recall), "mrr": rr / n, "stale": int(stale), "misses": misses}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--embedder", default=None)
    args = ap.parse_args()
    embedder = get_embedder(args.embedder)
    questions = [json.loads(line) for line in QUESTIONS.read_text().splitlines()]
    docs = ingest().docs
    status_of = {d.doc_id: d.status for d in docs}
    indexes = {name: Index.build([c for d in docs for c in fn(d)], embedder) for name, fn in STRATEGIES.items()}

    L = [f"# A4 retrieval grid (generated by `evals/run_a4_retrieval.py`, embedder `{embedder.name}`)", "",
         f"{len(questions)} questions ({sum(1 for q in questions if q['gold'])} answerable). Counts are out of "
         f"{sum(1 for q in questions if q['gold'])}; with this few questions, differences of one or two are within noise.", ""]
    for cond, statuses in CONDITIONS.items():
        L += [f"## Condition: {cond} (statuses searched: {', '.join(statuses)})", "",
              "| chunking | retriever | recall@3 | MRR | non-current top-1 | missed question ids |", "|---|---|---|---|---|---|"]
        for strat, index in indexes.items():
            for mode in MODES:
                r = evaluate(index, mode, statuses, questions, status_of)
                missed = ", ".join(f"{i}->{d}" for i, d in r["misses"]) or "-"
                L.append(f"| {strat} | {mode} | {r['recall']}/{r['n']} | {r['mrr']:.2f} | {r['stale']}/{r['n']} | {missed} |")
        L.append("")
    L += ["## Questions with no answer in the KB (top-1 chunk, default condition)", ""]
    for q in questions:
        if not q["gold"]:
            hits = indexes["structured"].search(q["q"], k=1, mode="hybrid", statuses=CURRENT)
            top = f"{hits[0].chunk.doc_id} (score {hits[0].score:.3f})" if hits else "nothing"
            L.append(f"- #{q['id']} {q['q']} -> {top}")
    GRID.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
